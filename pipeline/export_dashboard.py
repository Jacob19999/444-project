"""Export the snowflake-schema tables to dashboard/data.js for the front end.

The dashboard is a static page with no server, so the data ships as a script
that sets window.HEALTHCARE_DATA. One row per admission, stored column by
column, with every categorical field as a 0-based index into its dimension's
labels (dimension id - 1). That keeps the file near 2 MB and lets the page
filter and regroup all 54,966 admissions in the browser.

Run: python3 pipeline/export_dashboard.py   (after pipeline/build_schema.py)
"""

import json

import pandas as pd

from config import DASHBOARD_DATA_JS, SCHEMA_TABLES, TABLES_DIR
from verify_local import ddl_columns, foreign_keys


def labels(table: pd.DataFrame, col: str) -> list[str]:
    ids = table.iloc[:, 0]
    assert list(ids) == list(range(1, len(table) + 1)), "dimension ids must run 1..n"
    return table[col].tolist()


def main() -> None:
    t = {name: pd.read_csv(TABLES_DIR / f"{name}.csv", keep_default_na=False) for name in SCHEMA_TABLES}

    fact = t["fact_admission"].merge(
        t["dim_patient"][["patient_id", "gender_id", "blood_type_id"]], on="patient_id"
    ).sort_values("admission_id")
    start = pd.to_datetime(t["dim_date"]["full_date"]).min()
    admitted = pd.to_datetime(fact["admission_date_id"].astype(str), format="%Y%m%d")

    def index(col: str) -> list[int]:
        return (fact[col] - 1).tolist()

    data = {
        "meta": {
            "rows": len(fact),
            "start": start.strftime("%Y-%m-%d"),
            "source": "Kaggle: Healthcare Dataset (prasad22), synthetic",
            "tables": [
                {"name": name, "rows": len(t[name]), "columns": ddl_columns()[name]}
                for name in SCHEMA_TABLES
            ],
            "foreignKeys": [list(fk) for fk in foreign_keys()],
        },
        "dims": {
            "gender": labels(t["dim_gender"], "gender"),
            "blood": labels(t["dim_blood_type"], "blood_type"),
            "condition": labels(t["dim_medical_condition"], "medical_condition"),
            "insurer": labels(t["dim_insurance_provider"], "insurance_provider"),
            "admType": labels(t["dim_admission_type"], "admission_type"),
            "medication": labels(t["dim_medication"], "medication"),
            "test": labels(t["dim_test_result"], "test_result"),
            "ageGroup": labels(t["dim_age_group"], "age_group"),
        },
        "cols": {
            "gender": index("gender_id"),
            "blood": index("blood_type_id"),
            "condition": index("medical_condition_id"),
            "insurer": index("insurance_provider_id"),
            "admType": index("admission_type_id"),
            "medication": index("medication_id"),
            "test": index("test_result_id"),
            "ageGroup": index("age_group_id"),
            "age": fact["age_at_admission"].tolist(),
            "day": (admitted - start).dt.days.tolist(),  # days since meta.start
            "los": fact["length_of_stay_days"].tolist(),
            "billCents": (fact["billing_amount"] * 100).round().astype(int).tolist(),
        },
    }

    DASHBOARD_DATA_JS.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(data, separators=(",", ":"))
    DASHBOARD_DATA_JS.write_text(
        "// Generated by pipeline/export_dashboard.py from output/tables/. Do not edit.\n"
        f"window.HEALTHCARE_DATA = {payload};\n"
    )
    print(f"wrote {DASHBOARD_DATA_JS} ({DASHBOARD_DATA_JS.stat().st_size / 1e6:.1f} MB, {len(fact):,} admissions)")


if __name__ == "__main__":
    main()
